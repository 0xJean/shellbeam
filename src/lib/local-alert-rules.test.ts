import { describe, expect, it } from 'vitest'
import { actOnLocalAlert, EMPTY_LOCAL_ALERT_STATE, evaluateLocalAlertRules, localAlertNotificationEvent, normalizeLocalAlertRule, type LocalAlertObservation } from './local-alert-rules'
const rule = normalizeLocalAlertRule({ id: 'cpu', hostId: 'host', name: 'CPU high', metric: 'cpu', threshold: 90, recoveryThreshold: 80, durationMs: 10_000, recoveryDurationMs: 5_000, freshnessMs: 30_000 })
function observation(value: number | null, sampledAt: number): LocalAlertObservation[] { return [{ ruleId: rule.id, value, sampledAt, source: 'ssh-agentless', transport: 'proxy-jump' }] }
function evaluate(state = EMPTY_LOCAL_ALERT_STATE, value: number | null, at: number) { return evaluateLocalAlertRules(state, [rule], observation(value, at), at) }
describe('local rule alert lifecycle', () => {
  it('requires sustained fresh observations, ignores replay, deduplicates, acknowledges and recovers with hysteresis', () => {
    let state = evaluate(undefined, 95, 1_000)
    expect(state.alerts).toHaveLength(0)
    state = evaluateLocalAlertRules(state, [rule], observation(95, 1_000), 15_000)
    expect(state.alerts).toHaveLength(0)
    state = evaluate(state, 95, 11_000)
    expect(state.alerts[0]).toMatchObject({ status: 'active', transport: 'proxy-jump' })
    state = evaluate(state, 96, 12_000)
    expect(state.audit.map((row) => row.event)).toEqual(['opened'])
    state = actOnLocalAlert(state, rule.id, 'acknowledge', 13_000)
    state = evaluate(state, 85, 14_000)
    expect(state.alerts[0].status).toBe('acknowledged')
    state = evaluate(state, 75, 15_000)
    expect(state.evaluations[0].state).toBe('recovering')
    state = evaluate(state, 79, 20_000)
    expect(state.audit.map((row) => row.event)).toEqual(['opened', 'acknowledged', 'resolved'])
    expect(localAlertNotificationEvent(state.audit[2])).toMatchObject({ source: 'local-ops', kind: 'alert.resolved', metadata: { recovered: true } })
    state = evaluate(state, 95, 21_000)
    state = evaluate(state, 95, 31_000)
    expect(state.audit.at(-1)?.event).toBe('reopened')
  })
  it('unknown and stale samples break sustain evidence without resolving active incidents', () => {
    let state = evaluate(undefined, 99, 1_000)
    state = evaluate(state, null, 9_000)
    state = evaluate(state, 99, 12_000)
    expect(state.alerts).toHaveLength(0)
    state = evaluate(state, 99, 22_000)
    state = evaluate(state, 20, 23_000)
    state = evaluate(state, null, 24_000)
    expect(state.alerts[0].status).toBe('active')
    state = evaluateLocalAlertRules(state, [rule], observation(0, 25_000), 60_000)
    expect(state.alerts[0].status).toBe('active')
    expect(state.evaluations[0].state).toBe('unknown')
    state = evaluate(state, 0, 61_000)
    expect(state.alerts[0].status).toBe('active')
    state = evaluate(state, 0, 66_000)
    expect(state.alerts[0].status).toBe('resolved')
  })
  it('never counts a stale gap as sustained failure, and disabling does not invent recovery', () => {
    let state = evaluate(undefined, 99, 1_000)
    state = evaluate(state, 99, 40_000)
    expect(state.alerts).toHaveLength(0)
    state = evaluate(state, 99, 50_000)
    state = evaluateLocalAlertRules(state, [{ ...rule, enabled: false }], [], 60_000)
    expect(state.alerts[0].status).toBe('active')
    expect(state.evaluations[0].state).toBe('disabled')
  })
  it('supports binary service rules and bounds untrusted settings', () => {
    const service = normalizeLocalAlertRule({ id: 'nginx', hostId: 'host', name: 'nginx', metric: 'service', target: 'nginx.service', durationMs: 0, recoveryDurationMs: 0, threshold: 20, recoveryThreshold: 15, token: 'secret' })
    expect(service).toMatchObject({ threshold: 1, recoveryThreshold: 0 })
    expect(service).not.toHaveProperty('token')
    const state = evaluateLocalAlertRules(EMPTY_LOCAL_ALERT_STATE, [service], [{ ...observation(1, 10)[0], ruleId: service.id }], 10)
    expect(state.alerts[0].status).toBe('active')
    expect(() => normalizeLocalAlertRule({ ...service, target: 'x;rm' })).toThrow('local_alert_invalid_target')
  })

  it('requires a target for built-in ProbeProvider rules and fixes their binary thresholds', () => {
    const probe = normalizeLocalAlertRule({ id: 'probe:ssh-agentless:hash:metrics', hostId: 'host', name: 'Probe collection unavailable', metric: 'probe-provider', target: 'ssh-agentless:hash:metrics', threshold: 90, recoveryThreshold: 80, durationMs: 0, recoveryDurationMs: 0, token: 'secret' })
    expect(probe).toMatchObject({ metric: 'probe-provider', target: 'ssh-agentless:hash:metrics', threshold: 1, recoveryThreshold: 0 })
    expect(probe).not.toHaveProperty('token')
    for (const target of [undefined, '', '   ']) expect(() => normalizeLocalAlertRule({ ...probe, target })).toThrow('local_alert_invalid_target')
  })

  it('keeps ProbeProvider incidents open for unknown, invalid, stale or repeated values and preserves audited recovery', () => {
    const probe = normalizeLocalAlertRule({ id: 'probe:ssh-agentless:hash:metrics', hostId: 'host', name: 'Probe collection unavailable', metric: 'probe-provider', target: 'ssh-agentless:hash:metrics', durationMs: 0, recoveryDurationMs: 0, freshnessMs: 5_000 })
    const observed = (value: number | null, sampledAt: number) => [{ ruleId: probe.id, value, sampledAt, source: 'ssh-agentless', transport: 'proxy-jump' as const }]
    let state = evaluateLocalAlertRules(EMPTY_LOCAL_ALERT_STATE, [probe], observed(1, 1_000), 1_000)
    state = actOnLocalAlert(state, probe.id, 'acknowledge', 1_001, 'confirmed-ack-job')
    for (const value of [null, -1, 2, NaN]) {
      state = evaluateLocalAlertRules(state, [probe], observed(value, 2_000), 2_000)
      expect(state.alerts[0]).toMatchObject({ metric: 'probe-provider', status: 'acknowledged', source: 'ssh-agentless', transport: 'proxy-jump', operationJobId: 'confirmed-ack-job' })
      expect(state.evaluations[0].state).toBe('unknown')
    }
    state = evaluateLocalAlertRules(state, [probe], observed(0, 1_000), 2_000)
    state = evaluateLocalAlertRules(state, [probe], observed(0, 3_000), 10_000)
    expect(state.alerts[0].status).toBe('acknowledged')
    expect(state.audit.map(({ event }) => event)).toEqual(['opened', 'acknowledged'])
    state = evaluateLocalAlertRules(state, [probe], observed(0, 10_001), 10_001)
    expect(state.alerts[0]).toMatchObject({ status: 'resolved', source: 'ssh-agentless', transport: 'proxy-jump', operationJobId: 'confirmed-ack-job' })
    state = actOnLocalAlert(state, probe.id, 'close', 10_002, 'confirmed-close-job')
    expect(state.audit.map(({ event }) => event)).toEqual(['opened', 'acknowledged', 'resolved', 'closed'])
    expect(state.audit.slice(1).map(({ operationJobId }) => operationJobId)).toEqual(['confirmed-ack-job', 'confirmed-ack-job', 'confirmed-close-job'])
    expect(localAlertNotificationEvent(state.audit[2])).toMatchObject({ source: 'local-ops', kind: 'alert.resolved', metadata: { ruleId: probe.id, operationJobId: 'confirmed-ack-job', recovered: true } })
  })
})
