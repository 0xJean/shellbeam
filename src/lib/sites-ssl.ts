import type { HostProfile } from './hosts'
import type { CommandRunResult } from './sessions'
import { runWorkspaceRemoteCommand } from './workspace-remote'
import { operationTransport, runConfirmedOperation, type OperationJob } from './operation-job'

/** A conservative, read-only view of common reverse-proxy/site configuration. */
export type SiteServer = 'nginx' | 'apache' | 'caddy' | 'unknown'
export type SiteStatus = 'active' | 'configured' | 'unknown'
export type CertificateStatus = 'valid' | 'expiring' | 'expired' | 'unknown'

export interface SiteRecord {
  id: string
  hostId: string
  server: SiteServer
  name: string
  domains: string[]
  root?: string
  configPath?: string
  ssl: boolean
  status: SiteStatus
  observedAt: number
  transport: 'direct' | 'proxy-jump'
  provider: 'ssh-agentless'
}

export interface CertificateRecord {
  id: string
  hostId: string
  path: string
  subject: string
  issuer: string
  serial?: string
  domains: string[]
  notBefore: number | null
  notAfter: number | null
  daysRemaining: number | null
  status: CertificateStatus
  observedAt: number
  transport: 'direct' | 'proxy-jump'
  provider: 'ssh-agentless'
}

export interface SiteSslScanResult {
  hostId: string
  sites: SiteRecord[]
  certificates: CertificateRecord[]
  checkedAt: number
  durationMs: number | null
  transport: 'direct' | 'proxy-jump'
  provider: 'ssh-agentless'
  errorCode?: 'jump-unavailable' | 'auth' | 'network' | 'timeout' | 'command' | 'unknown'
  errorSummary?: string
}

export type SiteOperation = 'config-test' | 'reload'
export type CertificateOperation = 'renew-dry-run' | 'renew'

export interface SiteSslRunOptions {
  host: HostProfile
  resolveAuthSecret: (host: HostProfile) => Promise<string>
  now?: number
  runCommand?: (options: { host: HostProfile; resolveAuthSecret: (host: HostProfile) => Promise<string>; command: string }) => Promise<CommandRunResult>
}

const MAX_FIELD_LENGTH = 240
const EXPIRING_WITHIN_MS = 30 * 24 * 60 * 60 * 1000
const MAX_SCAN_LINES = 160

function shellQuote(value: string) {
  return `'${value.replace(/'/g, `'\\''`)}'`
}

function safeField(value: unknown, maxLength = MAX_FIELD_LENGTH) {
  return String(value ?? '')
    .replace(/[\r\n|]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, maxLength)
}

function transportFor(host: HostProfile): 'direct' | 'proxy-jump' {
  return host.jumpHost?.trim() ? 'proxy-jump' : 'direct'
}

function classifyError(error: unknown): SiteSslScanResult['errorCode'] {
  const message = String(error).toLowerCase()
  if (message.includes('jump') || message.includes('bastion')) return 'jump-unavailable'
  if (message.includes('auth') || message.includes('permission')) return 'auth'
  if (message.includes('timeout') || message.includes('timed out')) return 'timeout'
  if (message.includes('network') || message.includes('connect') || message.includes('handshake')) return 'network'
  if (message.includes('command') || message.includes('execute')) return 'command'
  return 'unknown'
}

function redactError(error: unknown) {
  return safeField(String(error ?? 'site_ssl_scan_failed').replace(/https?:\/\/[^\s]+/gi, '[url]'))
}

/**
 * Build one bounded, read-only remote probe. The marker format is intentionally
 * simple so it can be parsed without retaining complete server configuration or
 * certificate contents. Paths are generated by find on the remote host and are
 * always passed as quoted shell arguments.
 */
export const SITE_SSL_SCAN_COMMAND = `bash -lc ${shellQuote(`
set +e
emit_site() { printf '__SB_SITE=%s|%s|%s|%s|%s|%s|%s\\n' "$1" "$2" "$3" "$4" "$5" "$6" "$7"; }
emit_cert() { printf '__SB_CERT=%s|%s|%s|%s|%s|%s|%s|%s\\n' "$1" "$2" "$3" "$4" "$5" "$6" "$7" "$8"; }

if command -v nginx >/dev/null 2>&1; then
  nginx -T 2>/dev/null | awk '
    /server[[:space:]]*\\{/ { inside=1; names=""; root=""; ssl=0 }
    inside && /server_name[[:space:]]/ { line=$0; sub(/.*server_name[[:space:]]+/, "", line); sub(/[;{].*/, "", line); names=line }
    inside && /(^|[[:space:]])root[[:space:]]/ { line=$0; sub(/.*(^|[[:space:]])root[[:space:]]+/, "", line); sub(/[;{].*/, "", line); root=line }
    inside && /listen[[:space:]].*443|ssl/ { ssl=1 }
    inside && /^}[[:space:]]*$/ { if (names != "") printf "__SB_SITE=nginx|%s|%s|%s|%s|%s|%s\\n", names, root, ssl, "/etc/nginx/nginx.conf", names, "configured"; inside=0 }
  ' | head -n ${MAX_SCAN_LINES}
fi

if command -v apachectl >/dev/null 2>&1; then
  apachectl -S 2>/dev/null | awk '/namevhost|port [0-9]+ namevhost/ { host=$0; sub(/^.*\\*:[0-9]+[[:space:]]+/, "", host); sub(/[[:space:]]+\\(/, "", host); if (host != "") printf "__SB_SITE=apache|%s||||%s|configured\\n", host, host }' | head -n ${MAX_SCAN_LINES}
fi

if command -v caddy >/dev/null 2>&1 && [ -f /etc/caddy/Caddyfile ]; then
  awk 'NF && $0 !~ /^[[:space:]]*[#{}]/ && $0 !~ /^[[:space:]]+[a-z_]+/ { domain=$1; printf "__SB_SITE=caddy|%s||||%s|configured\\n", domain, domain }' /etc/caddy/Caddyfile | head -n ${MAX_SCAN_LINES}
fi

for cert in /etc/letsencrypt/live/*/fullchain.pem /etc/ssl/certs/*.pem; do
  [ -f "$cert" ] || continue
  subject=$(openssl x509 -in "$cert" -noout -subject 2>/dev/null | sed 's/^subject=//') || continue
  issuer=$(openssl x509 -in "$cert" -noout -issuer 2>/dev/null | sed 's/^issuer=//')
  serial=$(openssl x509 -in "$cert" -noout -serial 2>/dev/null | sed 's/^serial=//')
  start=$(openssl x509 -in "$cert" -noout -startdate 2>/dev/null | cut -d= -f2-)
  end=$(openssl x509 -in "$cert" -noout -enddate 2>/dev/null | cut -d= -f2-)
  [ -n "$end" ] || continue
  not_before=$(date -u -d "$start" +%s 2>/dev/null || printf '')
  not_after=$(date -u -d "$end" +%s 2>/dev/null || printf '')
  san=$(openssl x509 -in "$cert" -noout -ext subjectAltName 2>/dev/null | sed -n 's/.*DNS://p' | tr ',' ' ' | tr -d ' ')
  emit_cert "$cert" "$subject" "$issuer" "$serial" "$not_before" "$not_after" "$san" "openssl"
done | head -n ${MAX_SCAN_LINES}
`).trim()}`

function parseEpoch(value: string) {
  const parsed = Number(value)
  return Number.isFinite(parsed) && parsed > 0 ? parsed * 1000 : null
}

function parseStatus(notAfter: number | null, now: number): CertificateStatus {
  if (notAfter == null) return 'unknown'
  if (notAfter <= now) return 'expired'
  if (notAfter - now <= EXPIRING_WITHIN_MS) return 'expiring'
  return 'valid'
}

function parseDomains(value: string) {
  return value.split(/[ ,]+/).map((domain) => safeField(domain, 160)).filter(Boolean).slice(0, 32)
}

/** Parse only bounded marker lines; raw command output is deliberately ignored. */
export function parseSiteSslOutput(output: string, host: HostProfile, now = Date.now()): Pick<SiteSslScanResult, 'sites' | 'certificates'> {
  const sites: SiteRecord[] = []
  const certificates: CertificateRecord[] = []
  const transport = transportFor(host)

  output.split('\n').slice(0, MAX_SCAN_LINES * 2).forEach((line, index) => {
    if (line.startsWith('__SB_SITE=')) {
      const payload = line.slice('__SB_SITE='.length)
      const [server = 'unknown', names = '', root = '', sslFlag = '', configPath = '', name = '', status = 'configured'] = payload.split('|')
      const normalizedServer: SiteServer = server === 'nginx' || server === 'apache' || server === 'caddy' ? server : 'unknown'
      const domains = parseDomains(names)
      if (!domains.length) return
      sites.push({
        id: `${host.id}:site:${index}`,
        hostId: host.id,
        server: normalizedServer,
        name: safeField(name || domains[0]),
        domains,
        root: safeField(root) || undefined,
        configPath: safeField(configPath) || undefined,
        ssl: /^(1|true|yes)$/i.test(sslFlag) || /:443$/.test(names),
        status: status === 'active' ? 'active' : 'configured',
        observedAt: now,
        transport,
        provider: 'ssh-agentless',
      })
      return
    }
    if (!line.startsWith('__SB_CERT=')) return
    const payload = line.slice('__SB_CERT='.length)
    const [path = '', subject = '', issuer = '', serial = '', notBeforeRaw = '', notAfterRaw = '', domainsRaw = ''] = payload.split('|')
    if (!path) return
    const notBefore = parseEpoch(notBeforeRaw)
    const notAfter = parseEpoch(notAfterRaw)
    certificates.push({
      id: `${host.id}:cert:${index}`,
      hostId: host.id,
      path: safeField(path, 512),
      subject: safeField(subject),
      issuer: safeField(issuer),
      serial: safeField(serial) || undefined,
      domains: parseDomains(domainsRaw),
      notBefore,
      notAfter,
      daysRemaining: notAfter == null ? null : Math.ceil((notAfter - now) / (24 * 60 * 60 * 1000)),
      status: parseStatus(notAfter, now),
      observedAt: now,
      transport,
      provider: 'ssh-agentless',
    })
  })

  return { sites, certificates }
}

export async function runSiteSslScan(options: SiteSslRunOptions): Promise<SiteSslScanResult> {
  const now = options.now ?? Date.now()
  const startedAt = Date.now()
  const base = { hostId: options.host.id, sites: [], certificates: [], checkedAt: now, durationMs: null as number | null, transport: transportFor(options.host), provider: 'ssh-agentless' as const }
  try {
    const result = await (options.runCommand ?? runWorkspaceRemoteCommand)({ host: options.host, resolveAuthSecret: options.resolveAuthSecret, command: SITE_SSL_SCAN_COMMAND })
    const parsed = parseSiteSslOutput(result.stdout, options.host, now)
    return { ...base, ...parsed, durationMs: Math.max(0, result.durationMs || Date.now() - startedAt), ...(result.exitCode === 0 ? {} : { errorCode: 'command' as const, errorSummary: safeField(result.stderr || `exit=${result.exitCode}`) }) }
  } catch (error) {
    return { ...base, durationMs: Math.max(0, Date.now() - startedAt), errorCode: classifyError(error), errorSummary: redactError(error) }
  }
}

function safeSiteServer(server: SiteServer) {
  return server === 'nginx' || server === 'apache' || server === 'caddy' ? server : null
}

/** Commands are whitelisted so a site name or certificate path can never become shell syntax. */
export function buildSiteOperationCommand(site: Pick<SiteRecord, 'server'>, operation: SiteOperation) {
  const server = safeSiteServer(site.server)
  if (!server) throw new Error('site_operation_unsupported_server')
  const service = server === 'apache' ? 'apache2' : server
  if (operation === 'config-test') {
    if (server === 'nginx') return 'nginx -t 2>&1'
    if (server === 'caddy') return 'caddy validate --config /etc/caddy/Caddyfile 2>&1'
    return `${service}ctl configtest 2>&1`
  }
  return `systemctl reload ${service}`
}

export function buildCertificateOperationCommand(operation: CertificateOperation) {
  if (operation === 'renew-dry-run') return 'certbot renew --dry-run --non-interactive 2>&1'
  return 'certbot renew --non-interactive 2>&1'
}

export async function runSiteOperation(options: { host: HostProfile; resolveAuthSecret: (host: HostProfile) => Promise<string>; site: Pick<SiteRecord, 'server' | 'name'>; operation: SiteOperation; confirmMessage: string }) {
  const command = buildSiteOperationCommand(options.site, options.operation)
  return runConfirmedOperation({
    host: options.host,
    action: `site.${options.operation}`,
    target: safeField(options.site.name),
    risk: options.operation === 'reload' ? 'high' : 'read-only',
    paramsSummary: command,
    confirmMessage: options.confirmMessage,
    execute: () => runWorkspaceRemoteCommand({ host: options.host, resolveAuthSecret: options.resolveAuthSecret, command }),
    getResult: (result) => result,
    provider: 'ssh-agentless',
    transport: operationTransport(options.host),
    source: 'workspace',
  })
}

export async function runCertificateOperation(options: { host: HostProfile; resolveAuthSecret: (host: HostProfile) => Promise<string>; operation: CertificateOperation; confirmMessage: string }): Promise<{ value: CommandRunResult; job: OperationJob } | null> {
  const command = buildCertificateOperationCommand(options.operation)
  return runConfirmedOperation({
    host: options.host,
    action: `ssl.${options.operation}`,
    target: 'certbot',
    risk: options.operation === 'renew-dry-run' ? 'low' : 'high',
    paramsSummary: command,
    confirmMessage: options.confirmMessage,
    execute: () => runWorkspaceRemoteCommand({ host: options.host, resolveAuthSecret: options.resolveAuthSecret, command }),
    getResult: (result) => result,
    provider: 'ssh-agentless',
    transport: operationTransport(options.host),
    source: 'workspace',
  })
}
